function resolveColor(color) {
    if (typeof color === 'string' && /^#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?$/.test(color)) return color;
    if (typeof color === 'string' && /^[a-zA-Z][a-zA-Z0-9]*$/.test(color)) return 'var(--' + color + ')';
    return 'var(--txt)';
}

function iconSvg(key, color, cls) {
    // Bracket lookup finds inherited members, so an icon named "__proto__" or
    // "constructor" used to return a non-array and throw — and a name that
    // arrives in an imported file is persisted, so it threw on every launch.
    const paths = Object.prototype.hasOwnProperty.call(ICONS, key) ? ICONS[key] : ICONS.server;
    const inner = paths.map(d => `<path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="${d}"></path>`).join('');
    return `<svg class="${cls || 'w-4 h-4'}" style="color:${resolveColor(color)}" fill="none" stroke="currentColor" viewBox="0 0 24 24">${inner}</svg>`;
}

